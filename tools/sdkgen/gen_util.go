// goFile 组装生成文件：头部 + package + import（按正文引用推导）+ 正文，并格式化。
// doc 非空时作为包注释放在 package 之前；extra 为调用方补充的标记（如 chain 包 import）。
func goFile(pkg, doc, body string, extra map[string]importSpec) ([]byte, error) {
	var sb strings.Builder
	sb.WriteString(genHeader)
	if doc != "" {
		sb.WriteString(doc)
		if !strings.HasSuffix(doc, "\n") {
			sb.WriteString("\n")
		}
	}
	fmt.Fprintf(&sb, "package %s\n\n", pkg)
	sb.WriteString(importBlock(body, extra))
	sb.WriteString(body)
	return formatSource([]byte(sb.String()))
}

// writeGoFile 组装并写入生成文件（自动创建父目录）。
func writeGoFile(path, pkg, doc, body string, extra map[string]importSpec) error {
	src, err := goFile(pkg, doc, body, extra)
	if err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(path, src, 0o644); err != nil {
		return err
	}
	fmt.Fprintf(os.Stderr, "sdkgen: wrote %s\n", path)
	return nil
}

// importBlock 生成 import 块：stdlib 一组、外部一组，组内按路径排序。
func importBlock(body string, extra map[string]importSpec) string {
	markers := make(map[string]importSpec, len(importMarkers)+len(extra))
	for k, v := range importMarkers {
		markers[k] = v
	}
	for k, v := range extra {
		markers[k] = v
	}

	src := stripComments(body)
	var specs []importSpec
	for marker, spec := range markers {
		// 标记前不能是标识符字符或点，避免 "subtypes." 命中 "types."
		re := regexp.MustCompile(`(^|[^\p{L}\p{N}_.])` + regexp.QuoteMeta(marker))
		if re.MatchString(src) {
			specs = append(specs, spec)
		}
	}
	if len(specs) == 0 {
		return ""
	}

	var std, ext []string
	for _, spec := range specs {
		line := `"` + spec.Path + `"`
		if spec.Alias != "" {
			line = spec.Alias + " " + line
		}
		if isStdLib(spec.Path) {
			std = append(std, line)
		} else {
			ext = append(ext, line)
		}
	}
	sort.Strings(std)
	sort.Strings(ext)

	var sb strings.Builder
	sb.WriteString("import (\n")
	for _, line := range std {
		sb.WriteString("\t" + line + "\n")
	}
	if len(std) > 0 && len(ext) > 0 {
		sb.WriteString("\n")
	}
	for _, line := range ext {
		sb.WriteString("\t" + line + "\n")
	}
	sb.WriteString(")\n\n")
	return sb.String()
}

// isStdLib 判断 import 路径是否为标准库（首个路径段无点）。
func isStdLib(path string) bool {
	first := path
	if i := strings.Index(path, "/"); i >= 0 {
		first = path[:i]
	}
	return !strings.Contains(first, ".")
}

// stripComments 去掉 // 与 /* */ 注释（保留字符串字面量，避免误伤 "http://" 之类内容）。
func stripComments(src string) string {
	var sb strings.Builder
	sb.Grow(len(src))
	for i := 0; i < len(src); {
		c := src[i]
		switch {
		case c == '"' || c == '\'' || c == '`':
			quote := c
			sb.WriteByte(c)
			i++
			for i < len(src) {
				ch := src[i]
				sb.WriteByte(ch)
				i++
				if quote != '`' && ch == '\\' && i < len(src) {
					sb.WriteByte(src[i])
					i++
					continue
				}
				if ch == quote {
					break
				}
			}
		case c == '/' && i+1 < len(src) && src[i+1] == '/':
			for i < len(src) && src[i] != '\n' {
				i++
			}
		case c == '/' && i+1 < len(src) && src[i+1] == '*':
			i += 2
			for i < len(src) {
				if src[i] == '*' && i+1 < len(src) && src[i+1] == '/' {
					i += 2
					break
				}
				i++
			}
		default:
			sb.WriteByte(c)
			i++
		}
	}
	return sb.String()
}

// formatSource 格式化生成代码：优先 goimports（可用时），否则 go/format。
func formatSource(src []byte) ([]byte, error) {
	if path, err := exec.LookPath("goimports"); err == nil {
		cmd := exec.Command(path)
		cmd.Stdin = bytes.NewReader(src)
		var out, errBuf bytes.Buffer
		cmd.Stdout = &out
		cmd.Stderr = &errBuf
		if err := cmd.Run(); err != nil {
			return nil, fmt.Errorf("goimports failed: %v (%s)", err, errBuf.String())
		}
		return out.Bytes(), nil
	}
	return format.Source(src)
}

// UnderscoreToCamelCase 下划线命名 → 驼峰（与 go-ink-gen 一致，用于类型名与文件名）。
func UnderscoreToCamelCase(s string) string {
	parts := strings.Split(s, "_")
	var result string
	for _, part := range parts {
		if len(part) > 0 {
			runes := []rune(part)
			runes[0] = unicode.ToUpper(runes[0])
			result += string(runes)
		}
	}
	return result
}

// goKeywords Go 关键字（ABI 参数名不能直接用）。
var goKeywords = map[string]bool{
	"break": true, "case": true, "chan": true, "const": true, "continue": true,
	"default": true, "defer": true, "else": true, "fallthrough": true, "for": true,
	"func": true, "go": true, "goto": true, "if": true, "import": true,
	"interface": true, "map": true, "package": true, "range": true, "return": true,
	"select": true, "struct": true, "switch": true, "type": true, "var": true,
}

// goParamName ABI 参数名 → Go 形参名：空名用 argN，关键字与生成代码占用的名字加下划线后缀
// （params 是生成方法的参数名，c 是方法接收者）。
func goParamName(label string, i int) string {
	name := strings.TrimSpace(label)
	if name == "" {
		name = fmt.Sprintf("arg%d", i)
	}
	if goKeywords[name] || name == "params" || name == "c" {
		name += "_"
	}
	return name
}

// pkgNameOf 合约名 → Go 包名（小写，非字母数字转 _，首字符非字母前置 p）。
func pkgNameOf(contract string) string {
	var sb strings.Builder
	for _, r := range strings.ToLower(contract) {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9':
			sb.WriteRune(r)
		default:
			sb.WriteByte('_')
		}
	}
	name := sb.String()
	if name == "" {
		return "contract"
	}
	if name[0] >= '0' && name[0] <= '9' {
		return "p" + name
	}
	return name
}

// resolveChainImport chain 包 import 路径：显式指定优先，否则按 <out>/<chainDir> 相对最近
// go.mod 的模块路径推导。
func resolveChainImport(outDir, chainDir, override string) (string, error) {
	if override != "" {
		return override, nil
	}
	abs, err := filepath.Abs(filepath.Join(outDir, chainDir))
	if err != nil {
		return "", err
	}
	moduleDir, modulePath, err := findModule(abs)
	if err != nil {
		return "", fmt.Errorf("推导 chain 包 import 路径失败（%w），请用 -chain-import 指定", err)
	}
	rel, err := filepath.Rel(moduleDir, abs)
	if err != nil {
		return "", err
	}
	rel = filepath.ToSlash(rel)
	if rel == "." {
		return modulePath, nil
	}
	return modulePath + "/" + rel, nil
}

// findModule 自 dir 向上查找 go.mod，返回模块根目录与模块路径。
func findModule(dir string) (string, string, error) {
	for {
		goMod := filepath.Join(dir, "go.mod")
		if data, err := os.ReadFile(goMod); err == nil {
			for _, line := range strings.Split(string(data), "\n") {
				line = strings.TrimSpace(line)
				if rest, ok := strings.CutPrefix(line, "module "); ok {
					return dir, strings.TrimSpace(rest), nil
				}
			}
			return "", "", fmt.Errorf("go.mod 缺少 module 声明：%s", goMod)
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", "", fmt.Errorf("自 %s 向上未找到 go.mod", dir)
		}
		dir = parent
	}
}
