// 生成器共享工具：import 推导、格式化、路径与命名处理。
//
// 生成文件的 import 由正文引用推导（go/format 不增删 import，goimports 不保证安装），
// 因此正文里出现的 <pkg>. 标记必须与 importMarkers 一一对应。
